#!/usr/bin/env ruby
# frozen_string_literal: true

# Vendors the parts of Bootstrap that the shared nav needs, matching the markup used by the Community Engine
# gem (navbar, navbar-expand-lg, navbar-toggler, collapse navbar-collapse; data-bs-toggle="collapse").
#
# Bootstrap's reboot (box-sizing, line-height, heading margins, link colours) would restyle every page, so
# the full stylesheet is not used. This keeps only the navbar, nav-link and collapse rules (plus the :root
# variables they reference) and copies the JS bundle unchanged, all self-hosted under assets/vendor/bootstrap/.
#
#   ruby scripts/vendor_bootstrap_nav.rb [VERSION]   (default below; rewrites the three vendored files)
require 'net/http'
require 'digest'
require 'fileutils'

VERSION = (ARGV[0] || '5.3.3').freeze
CDN = "https://cdn.jsdelivr.net/npm/bootstrap@#{VERSION}"
OUT = File.expand_path('../assets/vendor/bootstrap', __dir__)

KEEP = /\A(\.navbar(?!-expand-(?:sm|md|xl|xxl))[\w-]*|\.nav|\.nav-link|\.collapse|\.collapsing|:root)\b/
DROP = /dropdown|offcanvas|nav-tabs|nav-pills|nav-underline|nav-fill|nav-justified|collapse-horizontal|navbar-expand-(?:sm|md|xl|xxl)/

def fetch(path)
  Net::HTTP.get(URI("#{CDN}/#{path}")).force_encoding('UTF-8')
end

# Splits CSS into top-level [prelude, body] pairs using brace depth.
def blocks(css)
  out = []
  depth = 0
  start = 0
  prelude = nil
  css.each_char.with_index do |c, i|
    if c == '{'
      prelude = css[start...i].strip if depth.zero?
      depth += 1
      body_start = i + 1 if depth == 1
      @body_start = body_start if body_start
    elsif c == '}'
      depth -= 1
      if depth.zero?
        out << [prelude, css[@body_start...i]]
        start = i + 1
      end
    end
  end
  out
end

def keep?(selector, body)
  return false if selector.start_with?(':root') && !body.include?('--bs-') # skip scroll-behavior and similar

  selector.split(',').map(&:strip).any? { |s| s.match?(KEEP) || s.start_with?('[data-bs-theme=light]') } &&
    !selector.match?(DROP)
end

def filter(css)
  kept = blocks(css).filter_map do |prelude, body|
    if prelude.start_with?('@media')
      inner = filter(body)
      "#{prelude} {\n#{inner}}\n" unless inner.strip.empty?
    elsif prelude.start_with?('@')
      nil
    elsif keep?(prelude, body)
      "#{prelude} {#{body}}\n"
    end
  end
  kept.join
end

css = fetch('dist/css/bootstrap.css').gsub(%r{/\*.*?\*/}m, '').sub(/@charset[^;]*;/, '')
subset = filter(css)
header = <<~H
  /*!
   * Bootstrap v#{VERSION} navbar, nav-link and collapse subset (MIT, see LICENSE).
   * Generated by scripts/vendor_bootstrap_nav.rb from #{CDN}/dist/css/bootstrap.css
   * Do not edit by hand; site-specific colours live in assets/styles/site.css.
   */
H
FileUtils.mkdir_p(OUT)
File.write(File.join(OUT, 'bootstrap-nav.css'), header + subset)
File.write(File.join(OUT, 'bootstrap.bundle.min.js'), fetch('dist/js/bootstrap.bundle.min.js'))
File.write(File.join(OUT, 'LICENSE'), fetch('LICENSE'))
puts "Vendored Bootstrap #{VERSION}: " + Dir[File.join(OUT, '*')].sort.map { |f| "#{File.basename(f)} #{File.size(f)}B" }.join(', ')
puts "sha256 bundle: #{Digest::SHA256.file(File.join(OUT, 'bootstrap.bundle.min.js')).hexdigest}"
